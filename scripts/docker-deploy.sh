#!/usr/bin/env bash
# GoForum one-click Docker deployment.
#
# Generates goforum.env (APP_KEY + GF_BACKUP_KEY), builds the image and starts
# the Compose stack, then waits for the container health check.
#
# Usage:
#   ./scripts/docker-deploy.sh
#   ./scripts/docker-deploy.sh --url https://forum.example.com --port 8080
#
set -Eeuo pipefail

ROOT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)"
ENV_FILE="$ROOT_DIR/goforum.env"
PORT="${GOFORUM_PORT:-}"
SITE_URL=""
VERSION="${GOFORUM_VERSION:-}"
BUILD=1
PORT_SET=0
URL_SET=0

log() { printf '\033[1;32m[goforum]\033[0m %s\n' "$*"; }
warn() { printf '\033[1;33m[goforum]\033[0m %s\n' "$*" >&2; }
die() { printf '\033[1;31m[goforum]\033[0m %s\n' "$*" >&2; exit 1; }

usage() {
  cat <<'EOF'
GoForum Docker 一键部署

用法：
  ./scripts/docker-deploy.sh [选项]

选项：
  --port PORT       宿主机端口（默认 8080）
  --url URL         站点公开地址，例如 https://forum.example.com
  --version VER     镜像版本标签（默认 dev）
  --no-build        不重新构建镜像，直接启动
  -h, --help        显示帮助

生成文件：
  goforum.env       APP_KEY、备份密钥与运行配置（0600，勿提交）
  goforum-data      Docker 命名卷，保存数据库、上传与配置
EOF
}

while (($#)); do
  case "$1" in
    --port) PORT="${2:?--port 需要端口}"; PORT_SET=1; shift 2 ;;
    --url) SITE_URL="${2:?--url 需要 URL}"; URL_SET=1; shift 2 ;;
    --version) VERSION="${2:?--version 需要值}"; shift 2 ;;
    --no-build) BUILD=0; shift ;;
    -h|--help) usage; exit 0 ;;
    *) die "未知参数：$1（使用 --help 查看帮助）" ;;
  esac
done

[[ -n "$VERSION" ]] || VERSION="${GOFORUM_VERSION:-dev}"
[[ "$VERSION" =~ ^[A-Za-z0-9._-]+$ ]] || die "版本号只能包含字母、数字、点、下划线和连字符"

command -v docker >/dev/null 2>&1 || die "未安装 Docker：https://docs.docker.com/engine/install/"
docker info >/dev/null 2>&1 || die "Docker 守护进程未运行，请先启动 Docker"

if docker compose version >/dev/null 2>&1; then
  COMPOSE=(docker compose)
elif command -v docker-compose >/dev/null 2>&1; then
  COMPOSE=(docker-compose)
else
  die "未找到 Docker Compose：请安装 docker compose 插件或 docker-compose"
fi

if [[ -n "$SITE_URL" && "${SITE_URL,,}" != https://* ]]; then
  die "公开站点请使用 https://；仅本机测试可先不带 --url，安装后再配置反向代理"
fi

if [[ ! -f "$ENV_FILE" ]]; then
  command -v openssl >/dev/null 2>&1 || die "缺少 openssl，无法生成密钥"
  [[ -n "$PORT" ]] || PORT=8080
  log "生成 $ENV_FILE"
  APP_KEY="$(openssl rand -base64 32)"
  BACKUP_KEY="$(openssl rand -base64 32)"
  {
    echo "# Generated by scripts/docker-deploy.sh on $(date -u '+%Y-%m-%dT%H:%M:%SZ')"
    echo "# Keep this file private. Back up APP_KEY and GF_BACKUP_KEY offline."
    echo "APP_ENV=production"
    [[ -n "$SITE_URL" ]] && echo "APP_URL=$SITE_URL"
    echo "APP_KEY=$APP_KEY"
    echo "HTTP_ADDR=:8080"
    echo "CACHE_STORE=memory"
    echo "FILESYSTEM_DISK=local"
    echo "STORAGE_PATH=/data/uploads"
    echo "LOG_LEVEL=info"
    echo "LOG_CHANNEL=json"
    echo "SESSION_COOKIE=gf_session"
    echo "WORKER_ENABLED=true"
    echo "GF_BACKUP_KEY=$BACKUP_KEY"
    echo "GOFORUM_PORT=$PORT"
  } >"$ENV_FILE"
  chmod 0600 "$ENV_FILE"
  GENERATED_SECRETS=1
else
  log "保留已有配置：$ENV_FILE"
  grep -q '^APP_KEY=.\+' "$ENV_FILE" || die "$ENV_FILE 缺少 APP_KEY"
  if [[ "$PORT_SET" == "1" ]]; then
    if grep -q '^GOFORUM_PORT=' "$ENV_FILE"; then
      sed -i "s|^GOFORUM_PORT=.*|GOFORUM_PORT=$PORT|" "$ENV_FILE"
    else
      printf 'GOFORUM_PORT=%s\n' "$PORT" >>"$ENV_FILE"
    fi
  fi
  if [[ "$URL_SET" == "1" ]]; then
    if grep -q '^APP_URL=' "$ENV_FILE"; then
      sed -i "s|^APP_URL=.*|APP_URL=$SITE_URL|" "$ENV_FILE"
    else
      printf 'APP_URL=%s\n' "$SITE_URL" >>"$ENV_FILE"
    fi
  fi
  GENERATED_SECRETS=0
fi
chmod 0600 "$ENV_FILE"

if [[ -z "$PORT" ]]; then
  PORT="$(sed -n 's/^GOFORUM_PORT=//p' "$ENV_FILE" | tail -1)"
  [[ -n "$PORT" ]] || PORT=8080
fi

export GOFORUM_PORT="$PORT"
export GOFORUM_VERSION="$VERSION"

cd "$ROOT_DIR"
log "启动 Docker Compose（端口 $PORT，版本 $VERSION）..."
if [[ "$BUILD" == "1" ]]; then
  "${COMPOSE[@]}" --env-file "$ENV_FILE" up -d --build
else
  "${COMPOSE[@]}" --env-file "$ENV_FILE" up -d
fi

CONTAINER_ID="$("${COMPOSE[@]}" --env-file "$ENV_FILE" ps -q goforum)"
[[ -n "$CONTAINER_ID" ]] || die "容器未创建，请检查 goforum.env 与 Compose 输出"

log "等待健康检查..."
HEALTHY=0
for _ in $(seq 1 60); do
  STATUS="$(docker inspect -f '{{if .State.Health}}{{.State.Health.Status}}{{else}}{{.State.Status}}{{end}}' "$CONTAINER_ID" 2>/dev/null || echo missing)"
  if [[ "$STATUS" == "healthy" ]]; then
    HEALTHY=1
    break
  fi
  if [[ "$STATUS" == "exited" || "$STATUS" == "dead" || "$STATUS" == "missing" ]]; then
    break
  fi
  sleep 2
done

if [[ "$HEALTHY" != "1" ]]; then
  warn "容器未通过健康检查，最近日志："
  "${COMPOSE[@]}" --env-file "$ENV_FILE" logs --tail=80 goforum >&2 || true
  die "启动失败，请根据日志排查"
fi

cat <<EOF

GoForum Docker 部署完成。

  安装向导 : http://127.0.0.1:${PORT}/install
  数据卷   : goforum-data（数据库、上传、goforum.yaml）
  配置文件 : $ENV_FILE

下一步：
  1. 打开安装向导，填写站点名称、公开 URL 与管理员账号。
  2. 公网部署请在前面加 Nginx/Caddy HTTPS 反向代理，并只暴露 443。
  3. 超管登录后绑定 TOTP，并保存恢复码。

常用命令：
  ${COMPOSE[*]} logs -f goforum
  ${COMPOSE[*]} restart goforum
  ${COMPOSE[*]} exec goforum /app/goforum backup
  ${COMPOSE[*]} down          # 停止并保留数据卷
  ${COMPOSE[*]} down -v       # 停止并删除数据（危险）

升级：
  git pull && ./scripts/docker-deploy.sh

EOF

if [[ "$GENERATED_SECRETS" == "1" ]]; then
  warn "本次生成了 APP_KEY 与 GF_BACKUP_KEY，已写入 $ENV_FILE。"
  warn "请立即把这两个值复制到密码管理器并离线保存；丢失 APP_KEY 会导致已加密设置与 TOTP 无法解密。"
fi
